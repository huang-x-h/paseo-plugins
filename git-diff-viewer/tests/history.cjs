const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cp = require('node:child_process');
const ts = require('typescript');

function load(file, dependencies = {}) {
  const source = fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const module = { exports: {} };
  new Function('require', 'exports', 'module', js)((name) => dependencies[name] ?? require(name), module.exports, module);
  return module.exports;
}
const diff = load('server/diff.ts');
const history = load('server/history.ts', { './diff': diff });
const repositories = load('server/repositories.ts', { './diff': diff });
const fileContent = load('server/file.ts', { './diff': diff });
const { matchingRemote } = load('client/branch-selection.ts');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'paseo-git-history-'));
const git = (...args) => cp.execFileSync('git', args, { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();

(async () => {
  try {
    const remoteBranches = ['origin/main', 'origin/feature/test', 'upstream/feature/test', 'upstream/other'].map((name) => ({ name, ref: `refs/remotes/${name}` }));
    assert.equal(matchingRemote('refs/heads/feature/test', remoteBranches, 'upstream/feature/test', 'feature/test'), 'refs/remotes/upstream/feature/test');
    assert.equal(matchingRemote('refs/heads/feature/test', remoteBranches, 'origin/main', 'main'), 'refs/remotes/origin/feature/test');
    assert.equal(matchingRemote('refs/heads/other', remoteBranches, '', 'main'), 'refs/remotes/upstream/other');
    assert.equal(matchingRemote('refs/heads/missing', remoteBranches, '', 'main'), '');
    assert.equal(matchingRemote('refs/heads/feature/test', remoteBranches.filter((item) => !item.name.startsWith('origin/')), '', ''), 'refs/remotes/upstream/feature/test');
    assert.equal(matchingRemote('refs/heads/feature/test', [{ name: 'one/feature/test', ref: 'one' }, { name: 'two/feature/test', ref: 'two' }], '', ''), '');
    git('init'); git('config', 'user.email', 'test@example.com'); git('config', 'user.name', 'Tester');
    fs.writeFileSync(path.join(dir, 'file name.txt'), 'first\n'); git('add', '.'); git('commit', '-m', 'initial');
    const first = git('rev-parse', 'HEAD');
    git('branch', 'other');
    fs.writeFileSync(path.join(dir, 'file name.txt'), 'second\n'); git('commit', '-am', 'second');
    const second = git('rev-parse', 'HEAD');
    await assert.rejects(diff.getDiff({ directory: dir, mode: 'upstream', file: null }), /上游/);
    git('remote', 'add', 'origin', 'https://example.invalid/repo.git');
    git('update-ref', 'refs/remotes/origin/test', first);
    const branchName = git('branch', '--show-current');
    git('config', `branch.${branchName}.remote`, 'origin');
    git('config', `branch.${branchName}.merge`, 'refs/heads/test');
    fs.writeFileSync(path.join(dir, 'file name.txt'), 'uncommitted\n');
    const upstreamDiff = await diff.getDiff({ directory: dir, mode: 'upstream', file: 'file name.txt' });
    assert.match(upstreamDiff.patch, /\+second/); assert.doesNotMatch(upstreamDiff.patch, /uncommitted/);
    const compareInput = { directory: dir, mode: 'branches', localRef: `refs/heads/${branchName}`, remoteRef: 'refs/remotes/origin/test' };
    const comparison = await diff.getDiff({ ...compareInput, file: 'file name.txt' });
    assert.match(comparison.patch, /-first/); assert.match(comparison.patch, /\+second/); assert.doesNotMatch(comparison.patch, /uncommitted/);
    const compareStats = await diff.getDiff({ ...compareInput, file: null });
    assert.equal(compareStats.additions, 1); assert.equal(compareStats.deletions, 1);
    const identical = await diff.getDiff({ ...compareInput, localRef: 'refs/heads/other', file: null });
    assert.deepEqual(identical.files, []);
    // A source-only commit must not appear as a deletion in the local branch's changes.
    const sourceTree = git('rev-parse', `${first}^{tree}`);
    const sourceCommit = cp.execFileSync('git', ['commit-tree', sourceTree, '-p', second, '-m', 'source only'], { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
    git('update-ref', 'refs/remotes/origin/diverged', sourceCommit);
    const sourceOnly = await diff.getDiff({ ...compareInput, remoteRef: 'refs/remotes/origin/diverged', file: null });
    assert.deepEqual(sourceOnly.files, []);
    const independent = cp.execFileSync('git', ['commit-tree', sourceTree, '-p', first, '-m', 'independent source'], { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
    git('update-ref', 'refs/remotes/origin/independent', independent);
    const divergent = await diff.getDiff({ ...compareInput, remoteRef: 'refs/remotes/origin/independent', file: 'file name.txt' });
    assert.match(divergent.patch, /-first/); assert.match(divergent.patch, /\+second/);
    await assert.rejects(diff.getDiff({ ...compareInput, localRef: '--all', file: null }), /有效/);
    await assert.rejects(diff.getDiff({ ...compareInput, remoteRef: 'refs/remotes/origin/missing', file: null }), /不存在/);
    const branchContent = await fileContent.getFileContent({ directory: dir, file: 'file name.txt', source: 'commit', revision: `refs/heads/${branchName}` });
    assert.match(branchContent.content, /second/); assert.doesNotMatch(branchContent.content, /uncommitted/);
    const branches = await history.getBranches({ directory: dir });
    assert(branches.branches.some((b) => b.ref === 'refs/heads/other'));
    const log = await history.getHistory({ directory: dir, ref: 'HEAD', skip: 0 });
    assert.deepEqual(log.commits.map((c) => c.hash), [second, first]);
    const other = await history.getHistory({ directory: dir, ref: 'refs/heads/other', skip: 0 });
    assert.deepEqual(other.commits.map((c) => c.hash), [first]);
    await assert.rejects(history.getHistory({ directory: dir, ref: '--all', skip: 0 }));
    const root = await history.getCommit({ directory: dir, hash: first, file: 'file name.txt' });
    assert.deepEqual(root.files, ['file name.txt']); assert.match(root.patch, /\+first/);
    const changed = await history.getCommit({ directory: dir, hash: second, file: 'file name.txt' });
    assert.match(changed.patch, /-first/); assert.match(changed.patch, /\+second/);
    const missing = await history.getCommit({ directory: dir, hash: second, file: 'missing' });
    assert.equal(missing.patch, '');
    fs.mkdirSync(path.join(dir, 'nested'));
    cp.execFileSync('git', ['init', path.join(dir, 'nested')], { stdio: 'ignore' });
    fs.writeFileSync(path.join(dir, 'untracked.txt'), 'new file\n');
    const changes = await diff.getDiff({ directory: dir, mode: 'unstaged', file: 'untracked.txt' });
    assert(changes.files.includes('untracked.txt')); assert.match(changes.patch, /\+new file/);
    const stats = await diff.getDiff({ directory: dir, mode: 'unstaged', file: null });
    assert.equal(stats.additions, 2); assert.equal(stats.deletions, 1);
    git('add', 'file name.txt');
    const stagedOnly = await diff.getDiff({ directory: dir, mode: 'unstaged', file: 'file name.txt' });
    assert.match(stagedOnly.patch, /\+uncommitted/);
    git('reset', '--hard', 'HEAD');
    const upstreamStats = await diff.getDiff({ directory: dir, mode: 'upstream', file: null });
    assert.equal(upstreamStats.additions, 1); assert.equal(upstreamStats.deletions, 1);
    const overview = await repositories.getRepositories({ directory: dir, roots: [] });
    assert.equal(overview.repositories.length, 2);
    const withExtra = await repositories.getRepositories({ directory: dir, roots: [path.join(dir, 'nested')] });
    assert.equal(withExtra.repositories.length, 2);
    const siblingRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'paseo-git-sibling-'));
    const docsOnly = path.join(siblingRoot, 'docs-only');
    fs.mkdirSync(docsOnly);
    fs.writeFileSync(path.join(docsOnly, 'notes.md'), 'notes\n');
    cp.execFileSync('git', ['init', path.join(siblingRoot, 'app')], { stdio: 'ignore' });
    const suggestion = await repositories.getRepositories({ directory: docsOnly, roots: [] });
    assert.equal(suggestion.repositories.length, 0);
    assert(suggestion.suggestions.some((item) => item.directory === path.resolve(siblingRoot) && item.repositoryCount === 1));
    const confirmed = await repositories.getRepositories({ directory: docsOnly, roots: [siblingRoot] });
    assert.equal(confirmed.repositories.length, 1);
    assert(confirmed.repositories[0].directory.includes('app'));
    fs.rmSync(siblingRoot, { recursive: true, force: true });
    const main = overview.repositories.find((repo) => repo.lastCommit.includes('second'));
    assert(main); assert(main.untracked >= 1); assert.equal(main.branch, branches.current); assert.match(main.lastCommit, /second/);
    fs.writeFileSync(path.join(dir, 'file name.txt'), 'worktree\n');
    const worktree = await fileContent.getFileContent({ directory: dir, file: 'file name.txt', source: 'worktree' });
    assert.match(worktree.content, /worktree/); assert.equal(worktree.binary, false);
    const committed = await fileContent.getFileContent({ directory: dir, file: 'file name.txt', source: 'commit', revision: second });
    assert.match(committed.content, /second/); assert.doesNotMatch(committed.content, /worktree/);
    await assert.rejects(fileContent.getFileContent({ directory: dir, file: '../outside.txt', source: 'worktree' }), /路径/);
    fs.writeFileSync(path.join(dir, 'binary.bin'), Buffer.from([0x00, 0x01, 0x02]));
    const binary = await fileContent.getFileContent({ directory: dir, file: 'binary.bin', source: 'worktree' });
    assert.equal(binary.binary, true); assert.equal(binary.content, '');
    console.log('Git history and multi-repository tests passed');
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
